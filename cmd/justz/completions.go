package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/igorlino/justz/internal/complete"
	"github.com/igorlino/justz/internal/help"
	"github.com/igorlino/justz/internal/shim"
)

const completionsUsage = `Usage: justz completions <zsh|bash>

Print a shell completion script for justz, the jz and jzh shortcuts, and every
registered shim. The script is small: it passes the words typed so far to
justz, which decides what can come next from the project's registry, so what
is completed always matches the project you are in.

  zsh:   put this in ~/.zshrc, after compinit:
           eval "$(justz completions zsh)"
  bash:  put this in ~/.bashrc:
           eval "$(justz completions bash)"

Run it again after adding or removing a shim, so the new names are included.

Exit codes: 0 done, 2 usage error.
`

func runCompletions(args []string, e env) int {
	if len(args) == 1 && (args[0] == "--help" || args[0] == "-h") {
		fmt.Fprint(e.stdout, completionsUsage)
		return 0
	}
	if len(args) != 1 || (args[0] != "zsh" && args[0] != "bash") {
		fmt.Fprint(e.stderr, "justz completions: expected one shell, zsh or bash\n\n"+completionsUsage)
		return 2
	}
	names := completionNames()
	if args[0] == "zsh" {
		fmt.Fprint(e.stdout, zshScript(names))
	} else {
		fmt.Fprint(e.stdout, bashScript(names))
	}
	return 0
}

// completionNames are the commands the script is registered for: justz, the
// built-in shortcuts and every registered shim with its help name.
func completionNames() []string {
	set := map[string]bool{"justz": true, "jz": true, "jzh": true}
	if d, err := shim.DefaultDirs(); err == nil {
		if reg, err := d.Load(); err == nil {
			for _, s := range reg.Shims {
				set[s.Name], set[s.HelpName()] = true, true
			}
		}
	}
	names := make([]string, 0, len(set))
	for n := range set {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

func zshScript(names []string) string {
	list := strings.Join(names, " ")
	return `#compdef ` + list + `
# Completion for justz and its shims. Generated by: justz completions zsh

_justz_complete() {
  local name=${words[1]:t}
  local -a lines cands
  local cur_words=("${(@)words[2,CURRENT]}")
  if [[ $name == justz ]]; then
    lines=("${(@f)$(justz __complete -- "${cur_words[@]}" 2>/dev/null)}")
  else
    lines=("${(@f)$(justz __complete --shim "$name" -- "${cur_words[@]}" 2>/dev/null)}")
  fi
  local files=0 l v d
  if [[ ${lines[1]} == ':files' ]]; then
    files=1
    lines=("${(@)lines[2,-1]}")
  fi
  for l in "${lines[@]}"; do
    [[ -z $l ]] && continue
    v=${l%%$'\t'*}
    d=''
    [[ $l == *$'\t'* ]] && d=${l#*$'\t'}
    v=${v//:/\\:}
    cands+=("$v:$d")
  done
  (( ${#cands} )) && _describe -t commands 'justz' cands
  (( files )) && _files
  return 0
}

if (( $+functions[compdef] )); then
  compdef _justz_complete ` + list + `
fi
`
}

func bashScript(names []string) string {
	list := strings.Join(names, " ")
	return `# Completion for justz and its shims. Generated by: justz completions bash

_justz_complete() {
  local name=${COMP_WORDS[0]##*/}
  local out line files=0
  if [[ $name == justz ]]; then
    out=$(justz __complete -- "${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null)
  else
    out=$(justz __complete --shim "$name" -- "${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null)
  fi
  COMPREPLY=()
  while IFS= read -r line; do
    [[ -z $line ]] && continue
    if [[ $line == ':files' ]]; then
      files=1
      continue
    fi
    COMPREPLY+=("${line%%$'\t'*}")
  done <<<"$out"
  if (( files )); then
    compopt -o filenames 2>/dev/null
    local f
    while IFS= read -r f; do COMPREPLY+=("$f"); done < <(compgen -f -- "${COMP_WORDS[COMP_CWORD]}")
  fi
}

complete -F _justz_complete ` + list + `
`
}

// runComplete is the hidden command the shell scripts call:
//
//	justz __complete [--shim NAME] -- <words typed after the command name>
//
// It prints one candidate per line as "value<TAB>description". A first line of
// ":files" asks the shell to complete file names too.
func runComplete(args []string, e env) int {
	shimName := ""
	if len(args) >= 2 && args[0] == "--shim" {
		shimName, args = args[1], args[2:]
	}
	if len(args) > 0 && args[0] == "--" {
		args = args[1:]
	}

	cenv := completeEnv(e, shimName)
	var res complete.Result
	switch {
	case shimName == "":
		res = complete.Justz(args, cenv)
	case shimName == "jz":
		res = complete.Shim(false, args, cenv)
	case shimName == "jzh":
		res = complete.Shim(true, args, cenv)
	default:
		d, err := shim.DefaultDirs()
		if err != nil {
			return 0
		}
		reg, err := d.Load()
		if err != nil {
			return 0
		}
		entry, isHelp, ok := findShim(reg, shimName)
		if !ok {
			return 0
		}
		_ = entry
		res = complete.Shim(isHelp, args, cenv)
	}

	if res.Files {
		fmt.Fprintln(e.stdout, ":files")
	}
	for _, c := range res.Candidates {
		desc := strings.NewReplacer("\t", " ", "\n", " ", "\r", " ").Replace(c.Desc)
		fmt.Fprintf(e.stdout, "%s\t%s\n", c.Value, desc)
	}
	return 0
}

// completeEnv builds the environment the completion logic reads. The project is
// the one around the working directory, or for a pinned shim the one of its
// justfile. Everything is loaded lazily, and a failure means no project.
func completeEnv(e env, shimName string) complete.Env {
	dir := func() string {
		if shimName != "" && shimName != "jz" && shimName != "jzh" {
			if d, err := shim.DefaultDirs(); err == nil {
				if reg, err := d.Load(); err == nil {
					if entry, _, ok := findShim(reg, shimName); ok {
						return filepath.Dir(entry.Justfile)
					}
				}
			}
		}
		cwd, _ := os.Getwd()
		return cwd
	}
	return complete.Env{
		Project: func() *help.Project {
			p, err := loadHelpProject(e, dir())
			if err != nil {
				return nil
			}
			return p
		},
		RootRecipes: func() map[string]bool {
			jf, err := shim.FindJustfile(dir())
			if err != nil {
				return nil
			}
			info, err := loadProject(e, jf)
			if err != nil || info == nil {
				return nil
			}
			return info.RootRecipes
		},
		Shims: func() []string {
			var out []string
			if d, err := shim.DefaultDirs(); err == nil {
				if reg, err := d.Load(); err == nil {
					for _, s := range reg.Shims {
						out = append(out, s.Name)
					}
				}
			}
			return out
		},
	}
}
