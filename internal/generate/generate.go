// Package generate builds the local overlay, a registry-shaped file derived
// from a native justfile, from the JSON that just --dump produces.
package generate

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/igorlino/justz/internal/orderedjson"
	"github.com/igorlino/justz/internal/registry"
)

type dump struct {
	Recipes map[string]recipe `json:"recipes"`
	Modules map[string]dump   `json:"modules"`
}

type recipe struct {
	Private    bool                         `json:"private"`
	Doc        *string                      `json:"doc"`
	Parameters []parameter                  `json:"parameters"`
	Attributes []map[string]json.RawMessage `json:"attributes"`
}

type parameter struct {
	Name  string  `json:"name"`
	Kind  string  `json:"kind"`
	Short *string `json:"short"`
	Long  *string `json:"long"`
	Help  *string `json:"help"`
	Flag  bool    `json:"flag"`
	Value *string `json:"value"`
}

// Result is what Build returns.
type Result struct {
	Doc      *orderedjson.Value
	Warnings []string
}

const comment = `Generated by justz generate from the justfile. Do not hand-edit; re-run it. Hand-added "values" lists are kept.`

// Arg is a documented parameter of a command.
type Arg struct {
	Name string
	Desc string
}

// Command is a public recipe with what the help views and the overlay need.
type Command struct {
	Name    string
	Desc    string
	Example string
	Heading string // the recipe's [group] attribute, a display heading only
	Args    []Arg
}

// Module is a top-level module and its public recipes.
type Module struct {
	Name      string
	Commands  []Command
	HasNested bool // the module has nested modules, which are not read
}

// Parsed is the content of a justfile dump: the root recipes and the
// top-level modules.
type Parsed struct {
	Core    []Command
	Modules []Module // sorted by name
}

// Parse reads the output of just --dump --dump-format json.
func Parse(dumpJSON []byte) (*Parsed, error) {
	var d dump
	if err := json.Unmarshal(dumpJSON, &d); err != nil {
		return nil, fmt.Errorf("could not understand the output of just --dump: %v", err)
	}
	p := &Parsed{Core: commandsOf(d.Recipes)}
	names := make([]string, 0, len(d.Modules))
	for n := range d.Modules {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		m := d.Modules[n]
		p.Modules = append(p.Modules, Module{Name: n, Commands: commandsOf(m.Recipes), HasNested: len(m.Modules) > 0})
	}
	return p, nil
}

func commandsOf(recipes map[string]recipe) []Command {
	var out []Command
	for name, r := range recipes {
		if r.Private {
			continue
		}
		desc, example := parseDoc(r.Doc)
		out = append(out, Command{Name: name, Desc: desc, Example: example, Heading: heading(r), Args: argSpecs(r.Parameters)})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// heading is the value of a recipe's [group] attribute, or "".
func heading(r recipe) string {
	for _, a := range r.Attributes {
		if raw, ok := a["group"]; ok {
			var g string
			if json.Unmarshal(raw, &g) == nil {
				return g
			}
		}
	}
	return ""
}

// Build turns the output of just --dump --dump-format json into a registry.
// Root recipes go in the "core" group and each top-level module becomes a
// group, because a group is also the path used to run its commands. existing,
// when not nil, is the previous output: any "values" lists added to its args by
// hand are carried over to the new one.
func Build(dumpJSON []byte, existing *orderedjson.Value) (Result, error) {
	parsed, err := Parse(dumpJSON)
	if err != nil {
		return Result{}, err
	}

	var res Result
	groups := obj()
	if core := commands(parsed.Core); len(core.Obj) > 0 {
		groups.Obj = append(groups.Obj, member("core", group("Core", core)))
	}
	for _, m := range parsed.Modules {
		if m.HasNested {
			res.Warnings = append(res.Warnings, fmt.Sprintf("module %q has nested modules, which are skipped: a group name is a single word", m.Name))
		}
		groups.Obj = append(groups.Obj, member(m.Name, group(m.Name, commands(m.Commands))))
	}

	doc := obj()
	doc.Obj = append(doc.Obj, member("$comment", str(comment)), member("groups", groups))
	if existing != nil {
		carryValues(doc, existing)
	}
	registry.Canonicalize(doc)
	res.Doc = doc
	return res, nil
}

func commands(cmds []Command) *orderedjson.Value {
	out := obj()
	for _, cmd := range cmds {
		c := obj()
		c.Obj = append(c.Obj, member("desc", str(cmd.Desc)))
		if cmd.Example != "" {
			c.Obj = append(c.Obj, member("example", str(cmd.Example)))
		}
		if len(cmd.Args) > 0 {
			args := &orderedjson.Value{Kind: orderedjson.Array, Arr: []*orderedjson.Value{}}
			for _, a := range cmd.Args {
				av := obj()
				av.Obj = append(av.Obj, member("name", str(a.Name)), member("desc", str(a.Desc)))
				args.Arr = append(args.Arr, av)
			}
			c.Obj = append(c.Obj, member("args", args))
		}
		out.Obj = append(out.Obj, member(cmd.Name, c))
	}
	return out
}

// parseDoc splits a doc string. The first line is the description. A line
// starting with "example:" gives the example: the text before a "|".
func parseDoc(doc *string) (desc, example string) {
	if doc == nil {
		return "", ""
	}
	lines := strings.Split(*doc, "\n")
	desc = lines[0]
	for _, l := range lines {
		if strings.HasPrefix(l, "example:") {
			example = strings.TrimSpace(strings.SplitN(strings.TrimPrefix(l, "example:"), "|", 2)[0])
			break
		}
	}
	return desc, example
}

// argSpecs lists the parameters that have help text. A parameter with a
// short or long name is an option: it shows its names and, when it takes a
// value, a placeholder. A parameter with a fixed value is a flag and takes
// none. Other parameters are positional.
func argSpecs(params []parameter) []Arg {
	var args []Arg
	for _, p := range params {
		if p.Help == nil {
			continue
		}
		var name string
		var spec []string
		if p.Short != nil {
			spec = append(spec, "-"+*p.Short)
		}
		if p.Long != nil {
			spec = append(spec, "--"+*p.Long)
		}
		switch {
		case len(spec) > 0 && (p.Flag || p.Value != nil):
			name = strings.Join(spec, ", ")
		case len(spec) > 0:
			name = strings.Join(spec, ", ") + " <" + p.Name + ">"
		case p.Kind == "star":
			name = "*" + p.Name
		case p.Kind == "plus":
			name = "+" + p.Name
		default:
			name = "<" + p.Name + ">"
		}
		args = append(args, Arg{Name: name, Desc: *p.Help})
	}
	return args
}

// carryValues copies "values" lists from args in the old file to args with
// the same group, command and name in the new one.
func carryValues(doc, old *orderedjson.Value) {
	oldGroups := old.Get("groups")
	newGroups := doc.Get("groups")
	if oldGroups == nil || newGroups == nil {
		return
	}
	for _, g := range newGroups.Obj {
		for _, kind := range []string{"commands"} {
			newCmds := g.Val.Get(kind)
			oldCmds := oldGroups.Get(g.Key).Get(kind)
			if newCmds == nil || oldCmds == nil {
				continue
			}
			for _, c := range newCmds.Obj {
				oldArgs := oldCmds.Get(c.Key).Get("args")
				newArgs := c.Val.Get("args")
				if oldArgs == nil || newArgs == nil || oldArgs.Kind != orderedjson.Array {
					continue
				}
				for _, na := range newArgs.Arr {
					nn := na.Get("name")
					for _, oa := range oldArgs.Arr {
						on, vals := oa.Get("name"), oa.Get("values")
						if nn != nil && on != nil && nn.Str == on.Str && vals != nil && vals.Kind == orderedjson.Array {
							na.Obj = append(na.Obj, member("values", vals))
						}
					}
				}
			}
		}
	}
}

func obj() *orderedjson.Value {
	return &orderedjson.Value{Kind: orderedjson.Object, Obj: []*orderedjson.Member{}}
}
func str(s string) *orderedjson.Value {
	return &orderedjson.Value{Kind: orderedjson.String, Str: s}
}
func member(k string, v *orderedjson.Value) *orderedjson.Member {
	return &orderedjson.Member{Key: k, Val: v}
}
func group(label string, cmds *orderedjson.Value) *orderedjson.Value {
	g := obj()
	g.Obj = append(g.Obj, member("label", str(label)), member("commands", cmds))
	return g
}
