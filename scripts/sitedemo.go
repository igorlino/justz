//go:build ignore

// Writes site/demo.js from the output of ./justz on testdata/site-demo, a rich
// project whose default recipe runs `justz help`, as `justz init --variant rich`
// writes it.
// Run `just site-demo` to regenerate; `just site-demo-check` fails when it is stale.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

type demo struct {
	Cmd string `json:"cmd"`
	Out string `json:"out"`
}

func main() {
	bin, _ := filepath.Abs("justz")
	fixture := filepath.Join("testdata", "site-demo")
	// jz and jzh are the binary started under those names; --local is the same
	// code path, so the demo needs no link. The last run is the JSON sample of
	// the agents section and has no tab.
	runs := []struct {
		cmd  string
		args []string
	}{
		{"jz", []string{"--local", "jz"}},
		{"jzh clean", []string{"--local", "jzh", "clean"}},
		{"jz clean", []string{"--local", "jz", "clean"}},
		{"justz check", []string{"check"}},
		{"justz lint", []string{"lint"}},
		{"justz help tool clean -j", []string{"help", "tool", "clean", "-j"}},
	}
	var demos []demo
	for _, r := range runs {
		var out bytes.Buffer
		c := exec.Command(bin, r.args...)
		c.Dir = fixture
		// The output must not depend on the shell that runs the generator.
		// Bare jz runs the default recipe, which calls justz: it must find this binary.
		c.Env = append(demoEnv(), "JUSTZ_QUIET=", "COLUMNS=80", "NO_COLOR=1",
			"PATH="+filepath.Dir(bin)+string(os.PathListSeparator)+os.Getenv("PATH"))
		c.Stdout, c.Stderr = &out, &out
		// check and lint exit non-zero on findings, and their output is the
		// point. A command that could not start is a broken demo.
		if err := c.Run(); err != nil {
			if _, ok := err.(*exec.ExitError); !ok || strings.HasPrefix(r.cmd, "jz") {
				fmt.Fprintf(os.Stderr, "sitedemo: %s: %v\n%s", r.cmd, err, out.String())
				os.Exit(1)
			}
		}
		demos = append(demos, demo{r.cmd, strings.TrimRight(out.String(), "\n")})
	}
	data, err := json.MarshalIndent(demos, "", "  ")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	js := "// Generated by scripts/sitedemo.go from the binary run on testdata/site-demo. Run `just site-demo`; do not edit by hand.\nwindow.JUSTZ_DEMOS = " + string(data) + ";\n"
	if err := os.WriteFile(filepath.Join("site", "demo.js"), []byte(js), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// demoEnv is the environment without the JUST_* settings of the caller, which
// change what just prints.
func demoEnv() []string {
	var env []string
	for _, kv := range os.Environ() {
		if !strings.HasPrefix(kv, "JUST_") {
			env = append(env, kv)
		}
	}
	return env
}
