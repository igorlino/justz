//go:build ignore

// Writes site/demo.js from the output of ./justz on testdata/variants/rich.
// Run `just site-demo` to regenerate; `just site-demo-check` fails when it is stale.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

type demo struct {
	Cmd string `json:"cmd"`
	Out string `json:"out"`
}

func main() {
	bin, _ := filepath.Abs("justz")
	fixture := filepath.Join("testdata", "variants", "rich")
	runs := [][]string{
		{"help"},
		{"check"},
		{"help", "core", "test"},
		{"lint"},
		{"help", "core", "test", "-j"},
	}
	var demos []demo
	for _, args := range runs {
		var out bytes.Buffer
		c := exec.Command(bin, args...)
		c.Dir = fixture
		c.Stdout, c.Stderr = &out, &out
		_ = c.Run() // check and lint exit non-zero on findings; the output is the point
		demos = append(demos, demo{"justz " + strings.Join(args, " "), strings.TrimRight(out.String(), "\n")})
	}
	data, err := json.MarshalIndent(demos, "", "  ")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	js := "// Generated by scripts/sitedemo.go from the binary run on testdata/variants/rich. Run `just site-demo`; do not edit by hand.\nwindow.JUSTZ_DEMOS = " + string(data) + ";\n"
	if err := os.WriteFile(filepath.Join("site", "demo.js"), []byte(js), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
